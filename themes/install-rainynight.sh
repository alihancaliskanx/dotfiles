#!/bin/bash
# Install the Rainy Night theme for Omarchy using HTTPS

echo "Installing Rainy Night theme..."

# Use the modern omarchy theme install command with HTTPS url
omarchy theme install https://github.com/alihancaliskanx/omarchy-rainynight-theme.git

echo "Theme installed successfully!"
echo "To apply the theme, run: omarchy theme set omarchy-rainynight-theme"
